import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, statSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { WorkbenchDatabase } from '../../packages/storage/dist/index.js';

const cache = resolve('cache');
mkdirSync(cache, { recursive: true });
const file = join(mkdtempSync(join(cache, 'event-recovery-')), 'workbench.db');
const db = new WorkbenchDatabase(file);
try {
  db.insertProject({ id: 'p', name: 'fixture', path: '.', toolchain: [], createdAt: '2026-09-06' });
  db.insertTask({ id: 't', projectId: 'p', prompt: '恢复', lifecycle: 'OPEN', executionState: 'IDLE', attentionState: 'NONE', worktreePath: null, worktreeBranch: null, createdAt: '2026-09-06' });
  const event = { id: 'e', type: 'TurnStarted', taskId: 't', turnId: 'turn', payload: {}, timestamp: '2026-09-06' };
  db.appendEvent(event, { executionState: 'RUNNING', attentionState: 'NONE' });
  assert.equal(db.appendEvent(event, { executionState: 'RUNNING', attentionState: 'NONE' }), false);
  assert.equal(db.getEvents('t').length, 1);
  assert.equal(db.getProjection('t').timelineSummary.length, 1);
  assert.throws(() => db.appendEvent({ ...event, type: 'TurnInterrupted' }), /冲突/);
  assert.equal(db.getTask('t').executionState, 'RUNNING');
  console.log('PASS: 重复事件无副作用；同 ID 不同内容拒绝');
  const before = db.getProjection('t');
  db.rebuildProjections();
  assert.deepEqual(db.getProjection('t'), before);
  assert.equal(db.getEvents('t').length, 1);
  db.recoverNonTerminalTasks();
  assert.equal(db.getTask('t').executionState, 'INTERRUPTED');
  assert.equal(db.getTask('t').attentionState, 'UNCERTAIN');
  assert.equal(db.getEvents('t').length, 2);
  db.recoverNonTerminalTasks();
  assert.equal(db.getEvents('t').length, 2);
  console.log('PASS: 重建不复制事件；中断恢复可重复执行');
  const input = db.recordInput('t', '请检查文件');
  assert.equal(db.listUncertainInputs().length, 0);
  db.recoverNonTerminalTasks();
  assert.equal(db.listUncertainInputs()[0].id, input.id);
  db.resolveInput(input.id, 'discard');
  assert.equal(db.listUncertainInputs().length, 0);
  assert.throws(() => db.resolveInput(input.id, 'resend'));
  db.saveRuntimeSession('t', 'thread-1', 'profile-1');
  assert.deepEqual(db.getRuntimeSession('t'), { threadId: 'thread-1', profileId: 'profile-1' });
  console.log('PASS: 未确认输入显式处理；Runtime 身份持久化');
  db.appendEvent({ id: 'large', type: 'ToolCompleted', taskId: 't', turnId: 'turn', payload: { output: 'a'.repeat(50 * 1024 * 1024) + '\n最后一行' }, timestamp: '2026-09-07' });
  const output = db.getEvents('t').find(event => event.id === 'large').payload.output;
  assert.equal(typeof output, 'object');
  assert.ok(output.tail.endsWith('最后一行'));
  assert.ok(output.tail.length <= 65536);
  assert.ok(statSync(join(file, '..', output.ref)).size <= 64 * 1024 * 1024);
  assert.ok(statSync(file).size < 1024 * 1024);
  console.log('PASS: 50MB 输出旁路文件，事件与 Renderer 仅携带受限 Tail');
  const savedEvents = db.getEvents('t');
  db.updateTaskStates('t', 'FAILED', 'NONE');
  db.rebuildProjections();
  assert.equal(db.getTask('t').executionState, 'INTERRUPTED');
  assert.deepEqual(db.getEvents('t'), savedEvents);
  console.log('PASS: 恢复任务状态使用已提交事件快照');
} finally { db.close(); }
